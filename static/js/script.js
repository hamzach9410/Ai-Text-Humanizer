document.addEventListener("DOMContentLoaded", function () {
  // DOM Elements
  const generateModeBtn = document.getElementById("generate-mode-btn");
  const humanizeModeBtn = document.getElementById("humanize-mode-btn");
  const inputText = document.getElementById("input-text");
  const inputTitle = document.getElementById("input-title");
  const inputTooltip = document.getElementById("input-tooltip");
  const submitBtn = document.getElementById("submit-btn");
  const submitText = document.getElementById("submit-text");
  const charCount = document.getElementById("char-count");
  const outputContent = document.getElementById("output-content");
  const outputInfo = document.getElementById("output-info");
  const copyBtn = document.getElementById("copy-btn");
  const downloadBtn = document.getElementById("download-btn");
  const clearBtn = document.getElementById("clear-btn");
  const loadingOverlay = document.getElementById("loading-overlay");
  const notification = document.getElementById("notification");
  const notificationText = document.getElementById("notification-text");
  const fileUpload = document.getElementById("file-upload");
  const fileName = document.getElementById("file-name");

  // Mode state
  let currentMode = "generate"; // 'generate' or 'humanize'

  // Initialize
  updateUIForMode();

  // Event Listeners
  generateModeBtn.addEventListener("click", () => switchMode("generate"));
  humanizeModeBtn.addEventListener("click", () => switchMode("humanize"));
  
  // Update UI when content type changes
  document.getElementById("content-type").addEventListener("change", updateUIForMode);

  inputText.addEventListener("input", function () {
    const length = this.value.length;
    charCount.textContent = `${length} characters`;

    if (length > 10000) {
      charCount.style.color = "var(--error)";
    } else if (length > 7000) {
      charCount.style.color = "var(--warning)";
    } else {
      charCount.style.color = "var(--gray)";
    }
  });

  submitBtn.addEventListener("click", processContent);

  copyBtn.addEventListener("click", copyOutput);
  downloadBtn.addEventListener("click", downloadOutput);
  clearBtn.addEventListener("click", clearOutput);

  fileUpload.addEventListener("change", handleFileUpload);

  // Allow Enter key to submit (but allow Shift+Enter for new lines)
  inputText.addEventListener("keydown", function (e) {
    if (e.key === "Enter" && !e.shiftKey) {
      e.preventDefault();
      processContent();
    }
  });

  // Functions
  function switchMode(mode) {
    if (mode === currentMode) return;

    currentMode = mode;

    // Update active button
    if (mode === "generate") {
      generateModeBtn.classList.add("active");
      humanizeModeBtn.classList.remove("active");
    } else {
      humanizeModeBtn.classList.add("active");
      generateModeBtn.classList.remove("active");
    }

    updateUIForMode();
  }

  function updateUIForMode() {
    const contentType = document.getElementById("content-type").value;
    
    if (currentMode === "generate") {
      inputTitle.textContent = "What would you like to create?";
      inputTooltip.textContent = "Enter a topic or prompt to generate human-like content";
      submitText.textContent = "Generate Content";
      
      // Update placeholder based on content type
      const placeholders = {
        'general': 'Enter your topic (e.g., "Benefits of renewable energy")',
        'email': 'Enter email topic (e.g., "Meeting request for project discussion")',
        'blog': 'Enter blog topic (e.g., "10 tips for remote work productivity")',
        'social': 'Enter social media topic (e.g., "Celebrating team achievements")',
        'story': 'Enter story idea (e.g., "A day in the life of a coffee shop owner")',
        'technical': 'Enter technical topic (e.g., "How to set up a REST API")'
      };
      
      inputText.placeholder = placeholders[contentType] || placeholders['general'];
    } else {
      inputTitle.textContent = "Paste your AI-generated text";
      inputTooltip.textContent = "Paste text generated by AI to convert it to human-like content";
      submitText.textContent = "Humanize Text";
      inputText.placeholder = "Paste your AI-generated text here...";
    }

    // Clear output
    clearOutput();
  }

  async function handleFileUpload(event) {
    const file = event.target.files[0];
    if (!file) return;

    // Check file size (max 16MB)
    if (file.size > 16 * 1024 * 1024) {
      showNotification("File size too large. Maximum 16MB allowed.", "error");
      return;
    }

    setLoading(true);
    fileName.textContent = `Uploading: ${file.name}...`;

    const formData = new FormData();
    formData.append("file", file);

    try {
      const response = await fetch("/upload", {
        method: "POST",
        body: formData,
      });

      const data = await response.json();

      if (!response.ok) {
        throw new Error(data.error || "Unknown error occurred");
      }

      // Populate the textarea with extracted text
      inputText.value = data.text;
      inputText.dispatchEvent(new Event("input")); // Trigger character count update

      fileName.textContent = `Uploaded: ${file.name}`;
      showNotification("File uploaded successfully! Text extracted.");
    } catch (error) {
      console.error("Error:", error);
      showNotification(error.message, "error");
      fileName.textContent = "";
    } finally {
      setLoading(false);
      // Reset file input
      fileUpload.value = "";
    }
  }

  async function processContent() {
    const text = inputText.value.trim();

    if (!text) {
      showNotification("Please enter some text to process", "error");
      return;
    }

    if (text.length > 10000) {
      showNotification(
        "Text is too long. Please limit to 10000 characters.",
        "error"
      );
      return;
    }

    const contentType = document.getElementById("content-type").value;
    const tone = document.getElementById("tone").value;

    // Show loading
    setLoading(true);

    try {
      const response = await fetch("/process", {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          mode: currentMode,
          text: text,
          content_type: contentType,
          tone: tone,
        }),
      });

      const data = await response.json();

      if (!response.ok) {
        throw new Error(data.error || "Unknown error occurred");
      }

      // Display the result with humanization info
      displayResult(data.result, data);
      
      // Show success message
      let message = currentMode === "generate" ? "Content generated successfully!" : "Text humanized successfully!";
      showNotification(message);
    } catch (error) {
      console.error("Error:", error);
      showNotification(error.message, "error");
      outputInfo.textContent = "Error processing your request";
    } finally {
      setLoading(false);
    }
  }

  function displayResult(text, data = {}) {
    const contentType = document.getElementById("content-type").value;
    
    // Format text based on content type
    let formattedText = formatText(text, contentType);
    
    outputContent.innerHTML = `<div class="humanized-content">${formattedText}</div>`;
    
    // Show simple status without technical details
    let statusText = `Content ready`;
    
    outputInfo.textContent = statusText;
  }

  function formatText(text, contentType = 'general') {
    // Handle different content type formatting
    if (contentType === 'email') {
      return formatEmailContent(text);
    } else if (contentType === 'blog') {
      return formatBlogContent(text);
    } else if (contentType === 'social') {
      return formatSocialContent(text);
    } else {
      return formatGeneralContent(text);
    }
  }
  
  function formatEmailContent(text) {
    // Format email with proper structure
    let formatted = text;
    
    // Add email styling
    formatted = formatted.replace(/^Subject:\s*(.+)$/gm, '<div class="email-subject"><strong>Subject:</strong> $1</div>');
    formatted = formatted.replace(/^(Dear|Hi)\s+(.+?),$$/gm, '<div class="email-greeting">$1 $2,</div>');
    formatted = formatted.replace(/^(Best regards|Thanks|Sincerely),?$/gm, '<div class="email-closing">$1,</div>');
    
    return `<div class="email-format">${formatted}</div>`;
  }
  
  function formatBlogContent(text) {
    // Format blog post with proper structure
    let formatted = text;
    
    // Convert markdown-style headers
    formatted = formatted.replace(/^# (.+)$/gm, '<h1 class="blog-title">$1</h1>');
    formatted = formatted.replace(/^## (.+)$/gm, '<h2 class="blog-heading">$1</h2>');
    formatted = formatted.replace(/^### (.+)$/gm, '<h3 class="blog-subheading">$1</h3>');
    
    // Format paragraphs
    const paragraphs = formatted.split('\n\n').map(p => {
      if (!p.trim() || p.includes('<h')) return p;
      return `<p class="blog-paragraph">${p.trim()}</p>`;
    });
    
    return `<div class="blog-format">${paragraphs.join('')}</div>`;
  }
  
  function formatSocialContent(text) {
    // Format social media content
    let formatted = text;
    
    // Convert hashtags
    formatted = formatted.replace(/#(\w+)/g, '<span class="hashtag">#$1</span>');
    
    // Convert mentions
    formatted = formatted.replace(/@(\w+)/g, '<span class="mention">@$1</span>');
    
    return `<div class="social-format">${formatted}</div>`;
  }
  
  function formatGeneralContent(text) {
    // Convert line breaks to paragraphs but preserve headings and formatting
    return text
      .split("\n\n")
      .map((paragraph) => {
        const trimmed = paragraph.trim();
        if (!trimmed) return "";

        // Check if this looks like a heading
        if (
          trimmed.startsWith("# ") ||
          trimmed.startsWith("## ") ||
          trimmed.startsWith("### ") ||
          trimmed.startsWith("#### ") ||
          trimmed.startsWith("##### ") ||
          trimmed.startsWith("###### ")
        ) {
          return `<h3>${trimmed.replace(/^#+\s/, "")}</h3>`;
        }

        // Preserve bold text and other formatting
        let formatted = trimmed.replace(
          /\*\*(.*?)\*\*/g,
          "<strong>$1</strong>"
        );
        formatted = formatted.replace(/\*(.*?)\*/g, "<em>$1</em>");
        formatted = formatted.replace(/\n/g, "<br>");

        return `<p>${formatted}</p>`;
      })
      .join("");
  }

  function copyOutput() {
    const text = outputContent.textContent;
    if (!text) return;

    navigator.clipboard
      .writeText(text)
      .then(() => {
        showNotification("Copied to clipboard!");
      })
      .catch((err) => {
        console.error("Failed to copy: ", err);
        showNotification("Failed to copy text", "error");
      });
  }

  function downloadOutput() {
    const text = outputContent.textContent;
    if (!text) return;

    const blob = new Blob([text], { type: "text/plain" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `textcraft-${currentMode}-${new Date().getTime()}.txt`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);

    showNotification("Download started!");
  }

  function clearOutput() {
    outputContent.innerHTML = `
            <div class="placeholder">
                <i class="fas fa-feather"></i>
                <p>Your content will appear here</p>
            </div>
        `;
    outputInfo.textContent = "Ready to generate";
  }

  function setLoading(isLoading) {
    if (isLoading) {
      loadingOverlay.classList.add("visible");
      submitBtn.disabled = true;
    } else {
      loadingOverlay.classList.remove("visible");
      submitBtn.disabled = false;
    }
  }

  function showNotification(message, type = "success") {
    notificationText.textContent = message;
    notification.className = "notification";

    if (type === "error") {
      notification.classList.add("error");
    }

    notification.classList.add("visible");

    setTimeout(() => {
      notification.classList.remove("visible");
    }, 3000);
  }
});
